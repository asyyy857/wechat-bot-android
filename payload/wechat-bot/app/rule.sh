#!/bin/bash
# ============================================================================
#  rule.sh —— 微信机器人「关键词规则」小工具
#
#  最常用：
#    bash rule.sh 骚 哪里骚了              # 看见「骚」就回「哪里骚了喵」（喵自动加）
#    bash rule.sh 撸 不要撸                # 看见「撸」就回「不要撸喵」
#    bash rule.sh 喵喵喵 老吴！ --no-meow   # 这条原样发，不加喵
#
#  看看 / 试跑 / 删除：
#    bash rule.sh --list                   # 列出所有规则
#    bash rule.sh --test "你好骚啊"         # 试跑一句话（不写文件，看命中哪条）
#    bash rule.sh --del 骚                 # 删除规则（按规则名或关键词）
#
#  可选参数：
#    --priority 58        越大越优先（默认 58）
#    --cooldown 120       同一条规则两次之间的最小间隔秒数（默认 120）
#    --mode contains      触发方式：contains 包含 / exact 全等 / regex 正则
#    --max-len 12         消息长度超过它就不触发
#    --reply "备选二"     再加一条候选回复（可重复，命中时随机抽一条）
#    --kw "别名"          再加一个关键词（可重复）
#    --no-meow            这条不加「喵」（默认加）
#    --mention-exempt     被 @ 时不走这条，交给模型
#    --image 哭,呜        改成发表情包（image_tag）
#    --force              关键词重复也照加
#    --no-wait            不等热重载确认
#
#  用法注意：关键词/回复里要用「多个」时写成 "a|b"（必须加引号，否则 | 是管道）
#
#  ★ 回复里自己带了「喵」也没关系（忘了规则表会自动加）：
#      · 结尾是「喵」   → 自动去掉，存成干净版，发送时统一加回（发出来一模一样）
#      · 「…喵！」这种  → 自动改成原样发（不再补喵）—— 怎么都不会出现两个喵
#
#  脚本自动做四件事：备份 rules.yaml → 文本插入（不动注释）→ 语法 + 实跑自校验
#  → 更新 mtime 触发热重载并等日志确认。校验不过会从备份自动回滚。
# ============================================================================
set -u
DIR="$(cd "$(dirname "$0")" && pwd)"
export TZ=Asia/Shanghai
exec python3 -u "$DIR/rule_tool.py" "$@"
