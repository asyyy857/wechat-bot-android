# ★ 2026-10-10：每次点击都往「直播页」上报坐标（用户能在页面上看到我点了哪儿）。
#   走 JSON body —— query 里带中文会被 http parser 丢掉（实测）。
#   后台执行 + 短超时：没起直播服务时也不拖慢流程。
live_report(){ curl -s -m 0.4 -X POST -H 'Content-Type: application/json' \
                 -d "$(printf '{"x":%s,"y":%s,"label":"%s"}' "$1" "$2" "${3:-}")" \
                 "http://127.0.0.1:${RIKE_LIVE_PORT:-18800}/click" >/dev/null 2>&1 & }
tap()       { node "$VS" -i "$SLOT" swipe "$1" "$2" "$1" "$(( $2 + 6 ))" 110 >/dev/null 2>&1
              live_report "$1" "$2" ''; }
# ★ 2026-10-10 加：**防吞点击** —— 点之前先等画面静止。
#   实测吞点击的主因不是注入方式（4 种方式 80~90%、差异在噪声内），而是
#   **"要新开面板/游戏在加载界面"时抑制输入**：同一批实验里关面板 16/16、
#   开面板只有 18/24（75%）。→ 别在加载的那几帧点。
#   settle 是纯采样（64px 小帧 + md5）、零 OCR，通常 0.3~0.6s；超时也照样点，不阻塞。
tap_safe()  { node "$PROBE" settle --still 2 --gap 80 --timeout "${3:-0.2}" >/dev/null 2>&1; tap "$1" "$2"; }
# ★ 2026-10-11：超时 0.6s → **0.2s**。依据（两条都是本机实测，不是理论）：
#   ① §9 第 2 条：44 次点击 A/B —— 直接点 22/22、先等静止再点 21/22，**无可测差异**；
#   ② §9 第 29 条：这游戏 UI 有持续动画，"连续 2 帧相同"**永远不成立** → settle 每轮
#      必等满超时（青崖书实测 timeout 3→3203ms、5→5171ms）。
#   → 所以这 0.6s 是**每次点击白烧**的（好感度一轮 10+ 次点击 ≈ 6s，整轮日课 30+ 次）。
#   不彻底删掉、只降到 0.2s：保留"万一正卡在加载态"的极小保险，成本几乎归零。
# ★ 2026-10-11：拟人化抖动 —— **固定节奏本身就是特征**。
#   依据（社区两个成熟项目的现成做法）：EVEBot 的 PulseTimer 在 Min/Max 之间取随机，
#   理由写得很直白「所有 bot 都用精确 2.000 秒 = 可疑」；clxTools 的自动演奏专门做了
#   「插入随机误差（伪装手弹）」。本脚本原来 0 处主动随机化，全是精确值。
#   rndsleep <秒> [抖动比例=0.3] → 实睡 秒×(1 ~ 1+比例)
#   ★ 抖动**只向上**（不做双向）：原来那些固定值都是实测标定的等待，双向抖动会让
#     实睡**比原值短**（如 sleep 1.5 变 1.05s）→ 可能引入"点太快被吞"的新风险。
#     只向上 = 永不快于原值，破坏固定节奏的效果一样，但没有引入新风险。
#   ⚠️ 两个环境坑（2026-10-11 实测）：① `sh` 是 **dash**，$RANDOM 是空的，不能用；
#      ② awk 裸调 srand() 靠时间做种，同秒多进程有撞车风险 → 显式用 /dev/urandom 取种。
#   兜底：awk/od 任一失败就退回原值，**绝不因为抖动把流程搞挂**。
rndsleep()  { _rnd_s=$(awk -v s="$1" -v j="${2:-0.3}" \
                -v r="$(od -An -N2 -tu2 /dev/urandom 2>/dev/null | tr -d ' ')" \
                'BEGIN{srand(r); printf "%.2f", s*(1+j*rand())}' 2>/dev/null)
              [ -n "$_rnd_s" ] || _rnd_s="$1"; sleep "$_rnd_s"; }

# ★ 2026-10-11：**只等不点**的等待原语 —— 死等（rndsleep N）的正解，用户点名的头号优化点。
#   为什么需要：像"点卡后等侠缘加载"这种，**画面什么时候到位事先不知道**；原来一律
#   `rndsleep 9` → 加载只要 3 秒也照样白等满 9 秒。
#   这里改成"每轮抓一帧、用**便宜的 ROI 判据**问一句到没到"，到了立刻走。
#   ⚠️ 三条纪律：
#     ① 判据必须便宜（ROI OCR ~60ms 可以；全屏 OCR 2~3s **别用**，见手册 §9 第 29 条）；
#     ② 循环里**只等不点**（要"点 + 验证"用 do_until）；
#     ③ 到点没到**不算失败** —— 返回 1 但流程继续（后面每步还有各自的验证兜底），
#        所以最坏情况只是"退化成原来的死等"，不会比原来更差。
wait_until() { c=$1; n=$2; d=$3; i=0
  while [ $i -lt "$n" ]; do
    i=$((i+1)); grab
    if $c; then echo "  ✅ $d（约 ${i} 轮）"; return 0; fi
    sleep 0.5
  done
  echo "  ⚠️ $d 等了 $n 轮仍未到 → 继续往下走（后续步骤各自还会验证）"; return 1; }
# ★ 2026-10-11：从 rike-account.sh **移植**「点→验证→没中补点」（原版只在那儿有，
#   日课主脚本里 31 处点击是裸的 —— 见手册 §9 第 2 条）。
#   为什么这个原语是对的：本机实测吞点击的主因**不是注入方式**（4 种方式 80~90%，
#   差异在噪声内），而是"新开面板/加载中被抑制输入"（关面板 16/16，**开面板只有 18/24**）。
#   所以点完必须验证、没中补点 —— 而不是靠"再点一次"或加大重试轮数（MaaNTE 的 pipeline
#   规范也把"盲目重试"列为禁止项：要找根因，不要同样的操作原样再来一遍）。
#   相对 rike-account.sh 原版的三处改进：① 用 grab 而非它的 snap；
#   ② 用 tap_safe（点前等画面静止 —— 正对"加载中被抑制"这个病根）；
#   ③ 间隔走 rndsleep，不带固定节奏。
#   $1=check函数名 $2=最多次数 $3=x $4=y $5=描述（check 通过即返回 0）
do_until()  { c=$1; n=$2; x=$3; y=$4; d=$5; i=0
              while [ $i -lt "$n" ]; do
                i=$((i+1)); grab
                if $c; then echo "  ✅ $d"; return 0; fi
                echo "  ▸ $d → 点 ($x,$y)（第 $i/$n 次）"; tap_safe "$x" "$y"; rndsleep 2.8
              done
              grab; $c && { echo "  ✅ $d"; return 0; }
              echo "  ❌ $d 失败（$n 次没生效）"; return 1; }
# ★ 2026-10-11：do_until 的**反向判据** —— 「已经不在青崖书了」。
