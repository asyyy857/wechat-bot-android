# ★ 2026-10-09：判"在不在青崖书"**不能只认「青崖书|日课点」** —— tesseract 把青崖书标题
#   读成"青崖韦 / 青岩书 / 上岩书"是常事（当天实测四种读法都出现过），于是脚本误判
#   "还没回到青崖书"→ 白白多绕好几轮（**漏报**，比误报更浪费）。
#   改成两层：① 放宽词表（青崖书里那些 OCR 读得稳的正文词）
#             ② scan 能认出卡片 —— 这是最硬的证据（认得出卡 = 一定站在青崖书）
in_qy() {   # 可选 $1 = 调用方**已经抓过的全屏 OCR 文本**（back 分支就是这样，复用它省一次 OCR）
  # ★★ 2026-10-10：改用**顶部 170px 带**（"青崖书"标题实测 (83,17)；"殊途同归…日课点"横幅 (814,18)）
  #   实测 2.77s vs 全屏 6.08s，**快一倍多**；而且**零误报** —— 标题页 / 角色选择页 / 账号面板 /
  #   段位页 / 初始化页在这条带上都读不出「青崖书|日课点」（5 个反例逐一实测）。
  # ⚠️ 判据里**故意不含「殊途同归」**：段位页标题就叫「段位（殊途同归）」，含它就必须再配排除词；
  #   而排除词踩过两次坑 ——「段位」会被青崖书自己的「活力领奖段位」命中（§9 第 44 条）。
  #   只用青崖书专有词，就不需要排除词了。
  _t=${1:-$(sh "$OCR" --roi "$QY_ROI" "$SHOT" 2>/dev/null)}
  printf '%s' "$_t" | grep -qE "$QY_TITLE_PAT" && return 0
  # ★ 2026-10-10 加固：光看 scan 退出码不稳（当天在侠缘界面被误判成"已在青崖书"，
  #   害得卡片自检读到「待做」→ 白重做一整轮）。改成**必须真读出一张卡名**才算数。
  # （pipeline 的退出码 = awk 的 exit；原来这里多写了一句 `return 1`，把兜底结果吞了）
  # ★★ 2026-10-11 修 bug：原来只要求「**≥1** 张卡名」，但 rike-cards.cjs 是用**编辑距离**
  #   把任意文字映射到最近的候选卡名（第 99~102 行）→ 它几乎永远吐得出一个名字：
  #   实测**侠缘界面把立绘读成「寻访?」**，于是被判成"读出了卡名" → in_qy **在侠缘上误判为真**。
  #   这就是上面 2026-10-10 那条"侠缘被误判成已在青崖书"的**真正根因**（当年加固的方向没修对）。
  #   → 收紧成 **≥2 张**：青崖书实测 5 张全认得出（4 个 fixture 全是 5），侠缘只有 1 张。
  scan 2>/dev/null | awk -F'\t' '$2 != "" && $2 !~ /读不出/ {n++} END{exit (n>=2 ? 0 : 1)}'
}

