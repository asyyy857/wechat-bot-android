  if printf '%s' "$_e" | grep -qE "$XIAYUAN_PAT"; then
    echo "  🚪 场景逃生：侠缘界面 → 点 ◇(61,36)"
    tap 61 36; sleep 2.5; return 0
  fi
  # ③.2 帖子详情页 —— **右上角菱形 ✕ (1297,66)**。
  #   ★2026-10-12 实测更正：手册旧结论"详情页没有能用的退出键"**是错的** ——
  #   当天试过 key back / 点世界地面 / 日课按钮 / am start **全部无效**，
  #   最后裁右上角放大才看到这个 ✕，**点一次就退回朋友圈列表**。
  #   判据用统计行专有词「送礼」（列表页实测不命中）。
  if printf '%s' "$_e" | grep -qE '送礼'; then
    echo "  🚪 场景逃生：帖子详情页 → 点右上角 ✕(1297,66)"
