    #   而当天「他人庄园」实测 (1076,158) **连点 7 次全空**、(1132,158) **一次就弹出确认框**（差 56px）。
    #   → 两个都点：先 (1132,158)（他人庄园），再 tap (1076,158)（菠萝农场，可能是旧场景的值）。
