# ⚠️ 副屏刚重建 / 游戏刚 am start 还没画第一帧时，原来一次抓不到就当场死。
grab()      { k=0; while [ $k -lt 5 ]; do
                rm -f "$SHOT"
                node "$VS" -i "$SLOT" shot "$SHOT" 2>&1 | grep -q '✅' && return 0
                k=$((k+1)); sleep 2
              done
              echo "❌ 抓帧失败（已重试 5 次）"; exit 1; }
