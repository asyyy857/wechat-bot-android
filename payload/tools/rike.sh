  #    ★2026-10-12 实测：不加这条时 `back` 要白试 2 步（◇→back，~35s）第 3 步才靠日课按钮穿透出来；
  #    判据用列表页专有词「猜你喜欢/按热度」（当天实测：青崖书/详情页都不会误命中）。
  if printf '%s' "$_e" | grep -qE '猜你喜欢|按热度'; then
    echo "  🚪 场景逃生：朋友圈浮层 → 点 ❮(750,276) 返回"
    tap 750 276; sleep 2.5; return 0
  fi
  # ④ 菠萝农场 / 他人庄园 —— 这两种场景**没有日课按钮**，
  #    右上角 (1076,158) 是「离开此地」（点了会弹确认框，下一轮由 ② 接手）
  if printf '%s' "$_e" | grep -qE '农场日志|农场简报|呵护太阳花|他人庄园|跨服庄园'; then
    echo "  🚪 场景逃生：农场/他人庄园 → 点「离开此地」(1076,158)"
