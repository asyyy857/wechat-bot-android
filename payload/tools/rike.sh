# rike.sh —— 逆水寒日课·副屏模式助手（副屏 1，1400x636）
#
# ==USAGE==
#   sh rike.sh cards              列 5 张卡（名称/是否目标/⟳坐标/状态）
#   sh rike.sh state              只看 5 张卡的状态（待做/领取/已领）
#   sh rike.sh auto [轮数=40] [张数=4]  自动刷到 N 张目标卡（只在「待做」态里刷）
#   sh rike.sh refresh <卡序...>  手动刷新指定卡
#   sh rike.sh do <玩法> <卡序>    做一个玩法：剧组|拍照|朋友圈|庄园|好感度|扮演派对
#   sh rike.sh back [步数=6]      通用「退回青崖书」（按画面特征选动作 + 每步验证）
#   sh rike.sh verify             确认日课"做过了"（卡片进「领取」态）——流程收尾用这个
#   sh rike.sh wake               检测待机画面并唤醒
#   sh rike.sh crop [文件]        裁卡片行（读图核对，省 token）
#   sh rike.sh claim [卡序...]    一键领奖（⚠️ 用户口径：领奖/日课点归用户，流程内不调用）
#   sh rike.sh talk [轮数=24]     盲推游历事件对话（⚠️ 游历归用户，需 RIKE_ALLOW_YOULI=1 才放行）
# ==END==
#
#   实测坐标（副屏 1400x636）:
#     卡中心 x = 547+141×(i-1)   ⟳ x = 598+141×(i-1), y=322
