#  ── 共性：这些**场景/全屏页**里 (1348,160) 不是日课按钮，硬点只会越走越偏。
#  ── 纪律（同干扰库）：① 命中**专有词**才动，绝不盲点；② 每次最多动一次手；
#     ③ 一次全屏 OCR（~2.5s）—— 只在"认不出 / 回不去"的路径上调用，不进正常快路径。
#  返回值：0 = 动了手（调用方要**重新抓帧**再判页面）；1 = 没有可逃的场景
# ══════════════════════════════════════════════════════════════════════════
escape_scene() {
  grab
  _e=$(sh "$OCR" "$SHOT" 2>/dev/null)
  # 已在青崖书就别乱动（这些动作的目标都是"离开非青崖书的场景"）
  printf '%s' "$_e" | grep -qE "$QY_TITLE_PAT" && return 1
  # ① 「音乐登录」模态弹窗 —— 它**吞掉一切点击**，OCR 能读出文案（今天进场卡死的元凶）
