#     空白收浮层统一用左下角 (20,615)；(1367,613) 会误触别的功能
#   等待界面用 tools/wait.sh "<关键字>" [超时] [间隔]，别死等 sleep。
#
#   环境变量：RIKE_SLOT(副屏号,默认1) RIKE_FORCE=1(跳过已完成保护) RIKE_NORETRY=1(自检不重做)
#            RIKE_ALLOW_XIAOZHEN=1 / RIKE_ALLOW_YOULI=1(放行归用户的玩法)
#
#   历史大坑（2026-10-08 大修）：待机检测词、拍照点 ◁ 最多 2 次、庄园「宠物」坐标、
#   claim 漏 100 节点、auto 缺界面校验。详见技能手册 §9。
