grab_smart(){ grab; if is_idle; then echo "  ⏸ 检测到待机画面 → 唤醒"; wake_now; grab; fi; }

# ══════════════════════════════════════════════════════════════════════════
#  全局干扰库（★2026-10-11 加）
#  ── 动机：今天几次"白跑"都不是步骤写错，而是**被某个浮层挡住、脚本还不知道**：
#     · 「欢迎层」吃掉 4 轮 ⇦（扮演派对，白烧 ~230s）
#     · 「热度浮层」延迟出现 → 点 ⇄ 全是白点（同一轮）
#     · 「新活动速递」自带遮罩，把日课按钮的点击**全吃掉**（白跑 5 轮）
#     · 「帖子详情页」吃掉朋友圈 19 个候选（~2 分钟）
#     · 待机画面吞掉**一切**输入
#     社区把这件事形式化成了同一套做法（MaaFramework 的 `[JumpBack]` 干扰节点、
#     实战总结里的"干扰库三分类 tap/wait/back + maxPerRun 防死循环"）：
#     **把临时挡路的界面做成一张表，动手之前按判据清一遍。**
#  ── 三条纪律（每条都是踩出来的，别放松）：
#     ① **每条必须有语义判据**，命中才动。绝不盲点 ✕ —— 实测"热度浮层不在时点
#        (1000,113) 会跳进 CC直播权益页"，越退越远（手册 §3.4）。
#     ② **不用排除词判据**（"没读到 X 就当没有"）—— 换 OCR 引擎会让它静默反转（§9 第 44 条）。
#     ③ 判据一律走**小 ROI**（~0.1s）；全屏 OCR（2~3s）不进这个循环（§9 第 29 条）。
#  ── 边界：只收"判据可靠 + 动作有明确归属"的条目。
#     · 「新活动速递」判据读不出来（整屏乱码）→ **不进库**，仍留在"回青崖书"那处
#       按上下文无脑点（那个坐标在主世界是空白，只在"要开青崖书"时用）。
#     · 「帖子详情页」的逃生动作是点日课按钮，而 (1348,160) 在小镇/角色属性页上
#       是「帮会」入口（§9 第 5 条）→ 动作有上下文风险，**也不进库**，留在朋友圈分支里。
#  ── 调用点（故意少而准）：`back` 每轮、`do` 尾部"回青崖书"循环每轮。
#     即"退出/找路"这条最容易卡住、也最需要自愈的路径上。
# ══════════════════════════════════════════════════════════════════════════
po_welcome(){ sh "$OCR" "$SHOT" --roi 300,30,600,420  2>/dev/null | grep -qE '欢迎来到'; }
po_hot()    { sh "$OCR" "$SHOT" --roi 330,40,440,400  2>/dev/null | grep -qE '热度|我要暖场|热度贡献'; }
# 返回值：0 = 清掉了东西（调用方宜"重新抓帧再判页面"，别拿旧帧下结论）；1 = 本来就干净
# ⚠️ 每次调用**最多动一次手**（宁可下一轮再来，也不连环误点）—— 外层调用点本身有轮数上限
#    （back 默认 6 步、do 尾部 4 轮），重复机会足够，不需要库内再套循环。
clear_popups() {
  grab
  if is_idle; then
    echo "  🧹 干扰库：待机画面（会吞掉一切输入）→ 唤醒"; wake_now; return 0
  fi
  if po_welcome; then
    echo "  🧹 干扰库：派对欢迎层 → 点空白(200,480) 关掉"; tap 200 480; sleep 2.5; return 0
  fi
  if po_hot; then
    echo "  🧹 干扰库：热度浮层 → 点 ✕(1000,113) 关掉"; tap 1000 113; sleep 2.5; return 0
  fi
  return 1
}
# ══════════════════════════════════════════════════════════════════════════
